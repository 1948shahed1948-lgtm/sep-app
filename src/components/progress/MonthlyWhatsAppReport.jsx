import React, { useState, useEffect } from 'react';
import { useLang } from '@/lib/i18n';
import { motion } from 'framer-motion';
import { MessageCircle, Loader2, Calendar } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { base44 } from '@/api/base44Client';

const MONTHS_AR = ['يناير', 'فبراير', 'مارس', 'أبريل', 'مايو', 'يونيو', 'يوليو', 'أغسطس', 'سبتمبر', 'أكتوبر', 'نوفمبر', 'ديسمبر'];
const MONTHS_EN = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

export default function MonthlyWhatsAppReport() {
  const { lang } = useLang();
  const [loading, setLoading] = useState(true);
  const [report, setReport] = useState('');
  const [hasData, setHasData] = useState(false);

  useEffect(() => {
    const build = async () => {
      try {
        const user = await base44.auth.me();
        const now = new Date();
        const monthStart = new Date(now.getFullYear(), now.getMonth(), 1);
        const monthLabel = lang === 'ar'
          ? `${MONTHS_AR[now.getMonth()]} ${now.getFullYear()}`
          : `${MONTHS_EN[now.getMonth()]} ${now.getFullYear()}`;

        const results = await base44.entities.QuizResult.filter({ user_id: user.id }, '-created_date', 100);
        const monthResults = results.filter(r => new Date(r.created_date) >= monthStart);
        const totalQuizzes = monthResults.length;
        const avgScore = totalQuizzes ? Math.round(monthResults.reduce((a, r) => a + (r.score_percentage || 0), 0) / totalQuizzes) : 0;
        const totalCorrect = monthResults.reduce((a, r) => a + (r.correct_count || 0), 0);
        const totalWrong = monthResults.reduce((a, r) => a + (r.wrong_count || 0), 0);

        const progress = await base44.entities.UserProgress.filter({ user_id: user.id }, '-updated_date', 300);

        const skillIds = [...new Set(progress.map(p => p.skill_id).filter(Boolean))];
        const lessonIds = [...new Set(progress.map(p => p.lesson_id).filter(Boolean))];
        const skillMap = {};
        const lessonMap = {};
        await Promise.all(skillIds.map(async (id) => { try { skillMap[id] = await base44.entities.Skill.get(id); } catch {} }));
        await Promise.all(lessonIds.map(async (id) => { try { lessonMap[id] = await base44.entities.Lesson.get(id); } catch {} }));

        const labelOf = (p) => {
          if (p.skill_id && skillMap[p.skill_id]) {
            return lang === 'ar' ? skillMap[p.skill_id].name_ar : skillMap[p.skill_id].name_en;
          }
          if (p.lesson_id && lessonMap[p.lesson_id]) {
            return lang === 'ar' ? lessonMap[p.lesson_id].title_ar : lessonMap[p.lesson_id].title_en;
          }
          return null;
        };

        const byLabel = {};
        progress.forEach(p => {
          const label = labelOf(p);
          if (!label) return;
          const m = p.mastery_percentage || 0;
          if (!byLabel[label] || m > byLabel[label]) byLabel[label] = m;
        });

        const mastered = Object.entries(byLabel).filter(([, m]) => m >= 80).sort((a, b) => b[1] - a[1]).slice(0, 8);
        const focus = Object.entries(byLabel).filter(([, m]) => m < 60).sort((a, b) => a[1] - b[1]).slice(0, 8);

        setHasData(totalQuizzes > 0 || Object.keys(byLabel).length > 0);

        const name = user?.full_name || (lang === 'ar' ? 'الطالب' : 'Student');
        const masteredLines = mastered.length
          ? mastered.map(([l, m]) => `✅ ${l} (${m}%)`).join('\n')
          : (lang === 'ar' ? '— لا توجد مهارات متقنة بعد هذا الشهر.' : '— No mastered skills yet this month.');
        const focusLines = focus.length
          ? focus.map(([l, m]) => `⚠️ ${l} (${m}%)`).join('\n')
          : (lang === 'ar' ? '— لا توجد نقاط ضعف واضحة. أحسنت!' : '— No clear weak spots. Well done!');

        const text = lang === 'ar'
          ? `📊 التقرير الشهري — بنوك الأسئلة والاختبارات\n\n👤 الطالب: ${name}\n📅 الشهر: ${monthLabel}\n\n— أداء الشهر —\n📝 اختبارات مكتملة: ${totalQuizzes}\n🎯 متوسط الدرجات: ${avgScore}%\n✅ إجابات صحيحة: ${totalCorrect}\n❌ إجابات خاطئة: ${totalWrong}\n\n🏅 المهارات المتقنة:\n${masteredLines}\n\n🎯 نقاط تحتاج إلى تركيز:\n${focusLines}\n\n— تم إنشاء التقرير تلقائياً من بنوك الأسئلة والاختبارات.`
          : `📊 Monthly Report — Saudi Education Platform\n\n👤 Student: ${name}\n📅 Month: ${monthLabel}\n\n— This Month's Performance —\n📝 Quizzes completed: ${totalQuizzes}\n🎯 Average score: ${avgScore}%\n✅ Correct answers: ${totalCorrect}\n❌ Wrong answers: ${totalWrong}\n\n🏅 Mastered skills:\n${masteredLines}\n\n🎯 Areas needing focus:\n${focusLines}\n\n— Auto-generated by the Saudi Education Platform.`;

        setReport(text);
      } catch {}
      setLoading(false);
    };
    build();
  }, [lang]);

  const url = `https://wa.me/?text=${encodeURIComponent(report)}`;

  if (loading) {
    return (
      <div className="flex items-center justify-center py-6 text-slate-400 gap-2 text-sm">
        <Loader2 className="w-4 h-4 animate-spin" />
        {lang === 'ar' ? 'جارٍ تجهيز التقرير الشهري...' : 'Preparing monthly report...'}
      </div>
    );
  }

  return (
    <motion.div
      initial={{ opacity: 0, y: 20 }}
      animate={{ opacity: 1, y: 0 }}
      className="rounded-2xl bg-gradient-to-br from-[#25D366]/10 to-emerald-50 border border-emerald-200 p-6"
    >
      <div className="flex items-start gap-3 mb-4">
        <div className="w-10 h-10 rounded-xl bg-[#25D366] flex items-center justify-center flex-shrink-0">
          <Calendar className="w-5 h-5 text-white" />
        </div>
        <div>
          <h3 className="font-heading font-bold text-slate-900">
            {lang === 'ar' ? 'التقرير الشهري عبر واتساب' : 'Monthly WhatsApp Report'}
          </h3>
          <p className="text-xs text-slate-500 mt-0.5">
            {lang === 'ar'
              ? 'شارك ملخصاً شهرياً عن المهارات المتقنة ونقاط التركيز مع ولي الأمر.'
              : 'Share a monthly summary of mastered skills and focus areas with parents.'}
          </p>
        </div>
      </div>

      {hasData ? (
        <motion.a href={url} target="_blank" rel="noopener noreferrer" className="block">
          <Button className="w-full gap-2 bg-[#25D366] hover:bg-[#1ebe5d] text-white border-0">
            <MessageCircle className="w-4 h-4" />
            {lang === 'ar' ? 'إرسال التقرير الشهري إلى واتساب' : 'Send monthly report to WhatsApp'}
          </Button>
        </motion.a>
      ) : (
        <p className="text-sm text-slate-500 text-center py-2">
          {lang === 'ar' ? 'لا توجد بيانات كافية لهذا الشهر بعد. ابدأ بالتدريب لإنشاء التقرير.' : 'Not enough data this month yet. Start practicing to build the report.'}
        </p>
      )}
    </motion.div>
  );
}
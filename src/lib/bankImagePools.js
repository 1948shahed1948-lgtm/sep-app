// ثم يعود لتدوير الصور العامة للأسئلة التي لم يُعثر لها على مطابقة.
import { EDU_IMAGES } from '@/lib/eduImages';

const BASE_POOL = Object.values(EDU_IMAGES);

// إزاحة مختلفة لكل مادة حتى تختلف الصور الاحتياطية بين البنوك
const SUBJECT_OFFSET = {
  science: 0,
  math: 41,
  lughati: 83,
  english: 127,
  islamic: 23,
  tawheed: 67,
  art: 109,
  lifeSkills: 151,
  general: 0,
};

// بادئات مفاتيح eduImages حسب المادة — يضمن أن الصور الاحتياطية
// تنتمي لنفس المادة فلا تظهر صورة غريبة (مثل حجر لسؤال عن المكعب).
const SUBJECT_PREFIXES = {
  math: ['M_'],
  science: ['S_', 'LF_', 'G_'],
  islamic: ['I_', 'G_'],
  tawheed: ['I_', 'G_'],
  english: ['E_', 'G_'],
  lughati: ['LA_', 'E_', 'G_'],
  art: ['A_', 'G_'],
  lifeSkills: ['L_', 'LF_', 'G_'],
  general: ['M_', 'S_', 'I_', 'E_', 'LA_', 'A_', 'L_', 'LF_', 'G_'],
};

function poolFor(subjectKey) {
  const prefixes = SUBJECT_PREFIXES[subjectKey] || SUBJECT_PREFIXES.general;
  const scoped = Object.entries(EDU_IMAGES)
    .filter(([k]) => prefixes.some((p) => k.startsWith(p)))
    .map(([, v]) => v);
  const base = scoped.length ? scoped : BASE_POOL;
  const off = SUBJECT_OFFSET[subjectKey] || 0;
  const n = base.length || 1;
  const out = [];
  for (let i = 0; i < 200; i++) out.push(base[(i + off) % n]);
  return out;
}


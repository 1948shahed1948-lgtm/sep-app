// يبني نص البحث من حقول السؤال المتعددة
function haystack(q, contextText) {
  const parts = [
    q.q_ar, q.question_ar, q.q_en, q.question_en,
    q.topic_ar, q.topic_en,
    Array.isArray(q.options_ar) ? q.options_ar.join(' ') : '',
    Array.isArray(q.pairs_ar) ? q.pairs_ar.map((p) => `${p.left} ${p.right}`).join(' ') : '',
    Array.isArray(q.matching_pairs_ar) ? q.matching_pairs_ar.map((p) => `${p.left} ${p.right}`).join(' ') : '',
    Array.isArray(q.items_ar) ? (q.items_ar[0]?.item || q.items_ar.join(' ')) : '',
    Array.isArray(q.classify_items_ar) ? q.classify_items_ar.map((p) => p.item || '').join(' ') : '',
    Array.isArray(q.categories_ar) ? q.categories_ar.join(' ') : '',
    Array.isArray(q.classify_categories_ar) ? q.classify_categories_ar.join(' ') : '',
    Array.isArray(q.ordering_items_ar) ? q.ordering_items_ar.join(' ') : '',
    contextText || '',
  ];
  return parts.filter(Boolean).join(' ');
}

function pickTopicImage(text) {
  if (!text) return null;
  for (const rule of TOPIC_RULES) {
    for (const k of rule.keys) {
      if (text.includes(k)) return EDU_IMAGES[rule.img] || null;
    }
  }
  return null;
}

/**
 * يأخذ مصفوفة أسئلة ويعيد نسخة مع image_url لكل سؤال يفتقدها.
 * - الأسئلة التي تملك صورة بالفعل تبقى كما هي.
 * - يُختار أولاً صورة مناسبة لموضوع السؤال من سجل eduImages.
 * - إن لم تُطابق أي موضوع، يُستخدم تدوير الصور العام للمادة.
 * @param {string} subjectKey مفتاح المادة لاختيار الإزاحة الاحتياطية.
 * @param {string} [contextText] نص إضافي (عنوان الدرس) لتحسين المطابقة.
 */
export function withQuestionImages(questions, subjectKey = 'general', contextText = '') {
  if (!Array.isArray(questions)) return questions;
  const pool = poolFor(subjectKey);
  return questions.map((q, i) => {
    if (q && q.image_url) return q;
    const text = haystack(q, contextText);
    const topicImg = pickTopicImage(text);
    return { ...q, image_url: topicImg || pool[i % pool.length] };
  });
}
const LangContext = createContext();

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('sep_lang') || 'ar');

  useEffect(() => {
    localStorage.setItem('sep_lang', lang);
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key) => translations[lang]?.[key] || translations.ar[key] || key;
  const isRTL = lang === 'ar';
  const toggleLang = () => setLang(lang === 'ar' ? 'en' : 'ar');
  const localizedField = (obj, field) => {
    if (!obj) return '';
    const suffix = lang === 'ar' ? '_ar' : '_en';
    return obj[field + suffix] || obj[field + '_ar'] || obj[field + '_en'] || '';
  };

  return (
    <LangContext.Provider value={{ lang, setLang, t, isRTL, toggleLang, localizedField }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  return useContext(LangContext);
}
export function getQuestionsForIslamicLesson(unitIdx, lessonIdx) {
  const unit = ISLAMIC_G1_S2_UNITS[unitIdx];
  if (!unit) return [];
  const lesson = unit.lessons[lessonIdx];
  if (!lesson) return [];
  return lesson.questions.map((q, i) => ({
    id: `${unit.id}_${lesson.id}_q${i}`,
    type: 'multiple_choice',
    question_ar: q.question_ar,
    options_ar: q.options_ar,
    correct_index: q.correct,
    explanation_ar: q.explanation_ar,
  }));
}